/**
 * 16×16 farm sprites, painted as SVG rects so they stay sharp when scaled.
 *
 * The catalogue in economy.ts still names each crop with an emoji — that is
 * a label, not a drawing. Everything on the farm is drawn from here.
 */

const FILL: Record<string, string> = {
  k: 'var(--p-k)',
  g: 'var(--p-g)',
  G: 'var(--p-G)',
  y: 'var(--p-y)',
  r: 'var(--p-r)',
  o: 'var(--p-o)',
  s: 'var(--p-s)',
  w: 'var(--p-w)',
  b: 'var(--p-b)',
  W: 'var(--p-W)',
  p: 'var(--p-p)',
};

function cells(map: string): { x: number; y: number; fill: string }[] {
  const out: { x: number; y: number; fill: string }[] = [];
  map
    .trim()
    .split('\n')
    .forEach((line, y) => {
      [...line.trim()].forEach((ch, x) => {
        const fill = FILL[ch];
        if (fill) out.push({ x, y, fill });
      });
    });
  return out;
}


export type SpriteId = keyof typeof SPRITES;

const CROPS: Record<string, SpriteId> = {
  wheat: 'wheat',
  corn: 'corn',
  tomato: 'tomato',
  pumpkin: 'pumpkin',
  goldgrain: 'goldgrain',
};

/** Which sprite a planting shows at this much growth. */
export function cropSprite(seedId: string, progress: number): SpriteId {
  if (progress >= 1) return CROPS[seedId] ?? 'wheat';
  if (progress >= 0.6) return 'filling';
  if (progress >= 0.25) return 'sprout';
  return 'seed';
}

export function asSprite(id: string): SpriteId {
  return id in SPRITES ? (id as SpriteId) : 'plus';
}

export function Pixel({
  sprite,
  size = 16,
  className,
}: {
  sprite: SpriteId;
  size?: number;
  className?: string;
}) {
  return (
    <svg
      className={className ? `px-icon ${className}` : 'px-icon'}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      aria-hidden
    >
      {SPRITES[sprite].map((cell, i) => (
        <rect key={i} x={cell.x} y={cell.y} width={1} height={1} fill={cell.fill} />
      ))}
    </svg>
  );
}
